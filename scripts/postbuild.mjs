import { copyFileSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

/**
 * GitHub Pages has no server-side routing, so a direct visit to a nested route
 * (for example /Nexora/books/some-slug) returns 404.html. Serving a copy of
 * index.html there lets the client router resolve the path instead.
 */
const dist = join(process.cwd(), 'dist');
const index = join(dist, 'index.html');
const notFound = join(dist, '404.html');

if (!existsSync(index)) {
  console.error('postbuild: dist/index.html not found — run the build first.');
  process.exit(1);
}

copyFileSync(index, notFound);

const notice = '<!-- Generated by scripts/postbuild.mjs as the SPA fallback for GitHub Pages. -->\n';
writeFileSync(notFound, notice + readFileSync(notFound, 'utf8'));

console.log('postbuild: wrote dist/404.html (SPA fallback).');

/**
 * robots.txt points at /Nexora/sitemap.xml, so the file has to exist or that
 * reference is a dead link. Only routes that render for an anonymous visitor
 * are listed; the admin and account areas are already disallowed in robots.txt
 * and are deliberately left out.
 */
const SITE = 'https://shawonhaque.github.io/Nexora';

const PUBLIC_ROUTES = [
  ['/', '1.0', 'weekly'],
  ['/explore', '0.9', 'weekly'],
  ['/search', '0.7', 'monthly'],
  ['/world', '0.8', 'daily'],
  ['/technology', '0.8', 'daily'],
  ['/ai', '0.8', 'daily'],
  ['/science', '0.8', 'daily'],
  ['/education', '0.8', 'daily'],
  ['/business', '0.8', 'daily'],
  ['/knowledge', '0.7', 'weekly'],
  ['/learning', '0.7', 'weekly'],
  ['/books', '0.7', 'weekly'],
  ['/study', '0.7', 'weekly'],
  ['/writing', '0.7', 'weekly'],
  ['/ideas', '0.6', 'weekly'],
  ['/news', '0.6', 'weekly'],
  ['/about', '0.6', 'monthly'],
];

const today = new Date().toISOString().slice(0, 10);

const sitemap = [
  '<?xml version="1.0" encoding="UTF-8"?>',
  '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
  ...PUBLIC_ROUTES.map(
    ([path, priority, changefreq]) =>
      `  <url><loc>${SITE}${path === '/' ? '/' : path}</loc>` +
      `<lastmod>${today}</lastmod>` +
      `<changefreq>${changefreq}</changefreq>` +
      `<priority>${priority}</priority></url>`
  ),
  '</urlset>',
  '',
].join('\n');

writeFileSync(join(dist, 'sitemap.xml'), sitemap);
console.log(`postbuild: wrote dist/sitemap.xml (${PUBLIC_ROUTES.length} routes).`);
