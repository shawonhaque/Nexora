import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

/**
 * GitHub Pages has no server-side routing. Two problems follow, and both are
 * fixed here from the same route list.
 *
 * 1. A direct visit to a nested route returns 404.html. GitHub Pages serves a
 *    directory's index.html for the matching path, so writing a copy of
 *    index.html into each route's directory makes /Nexora/explore resolve with
 *    a 200 instead of a soft 404. The bundled asset URLs are absolute
 *    (/Nexora/assets/...), so a copy in a subdirectory still loads them.
 *
 * 2. Routes with a parameter cannot be enumerated, so they fall through to
 *    404.html, which is the same document and resolves client-side.
 */
const dist = join(process.cwd(), 'dist');
const index = join(dist, 'index.html');

if (!existsSync(index)) {
  console.error('postbuild: dist/index.html not found — run the build first.');
  process.exit(1);
}

const shell = readFileSync(index, 'utf8');
const notice = '<!-- Generated by scripts/postbuild.mjs as the SPA fallback for GitHub Pages. -->\n';

const SITE = 'https://shawonhaque.github.io/Nexora';

/**
 * Every static route the router can match. `public: true` marks the pages that
 * render for an anonymous visitor and belong in the sitemap; the account and
 * admin areas are reachable but excluded from it and disallowed in robots.txt.
 */
const ROUTES = [
  { path: '/', public: true, priority: '1.0', changefreq: 'weekly' },
  { path: '/explore', public: true, priority: '0.9', changefreq: 'weekly' },
  { path: '/search', public: true, priority: '0.7', changefreq: 'monthly' },
  { path: '/world', public: true, priority: '0.8', changefreq: 'daily' },
  { path: '/technology', public: true, priority: '0.8', changefreq: 'daily' },
  { path: '/ai', public: true, priority: '0.8', changefreq: 'daily' },
  { path: '/science', public: true, priority: '0.8', changefreq: 'daily' },
  { path: '/education', public: true, priority: '0.8', changefreq: 'daily' },
  { path: '/business', public: true, priority: '0.8', changefreq: 'daily' },
  { path: '/knowledge', public: true, priority: '0.7', changefreq: 'weekly' },
  { path: '/learning', public: true, priority: '0.7', changefreq: 'weekly' },
  { path: '/books', public: true, priority: '0.7', changefreq: 'weekly' },
  { path: '/study', public: true, priority: '0.7', changefreq: 'weekly' },
  { path: '/study/resources', public: true, priority: '0.6', changefreq: 'weekly' },
  { path: '/writing', public: true, priority: '0.7', changefreq: 'weekly' },
  { path: '/ideas', public: true, priority: '0.6', changefreq: 'weekly' },
  { path: '/news', public: true, priority: '0.6', changefreq: 'weekly' },
  { path: '/about', public: true, priority: '0.6', changefreq: 'monthly' },
  { path: '/saved', public: false },
  { path: '/history', public: false },
  { path: '/profile', public: false },
  { path: '/settings', public: false },
  { path: '/bookmarks', public: false },
  { path: '/login', public: false },
  { path: '/admin', public: false },
];

// 1. Per-route shell so nested routes resolve with a 200.
let written = 0;
for (const route of ROUTES) {
  if (route.path === '/') continue;
  const target = join(dist, route.path.slice(1), 'index.html');
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, notice + shell);
  written += 1;
}
console.log(`postbuild: wrote ${written} route shells (nested routes now resolve with 200).`);

// 2. 404.html for the routes that cannot be enumerated (parameterised paths).
copyFileSync(index, join(dist, '404.html'));
writeFileSync(join(dist, '404.html'), notice + shell);
console.log('postbuild: wrote dist/404.html (SPA fallback for parameterised routes).');

// 3. Sitemap — robots.txt points at it, so it must exist.
const today = new Date().toISOString().slice(0, 10);

const sitemap = [
  '<?xml version="1.0" encoding="UTF-8"?>',
  '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
  ...ROUTES.filter((route) => route.public).map(
    ({ path, priority, changefreq }) =>
      `  <url><loc>${SITE}${path}</loc>` +
      `<lastmod>${today}</lastmod>` +
      `<changefreq>${changefreq}</changefreq>` +
      `<priority>${priority}</priority></url>`
  ),
  '</urlset>',
  '',
].join('\n');

writeFileSync(join(dist, 'sitemap.xml'), sitemap);
console.log(
  `postbuild: wrote dist/sitemap.xml (${ROUTES.filter((r) => r.public).length} public routes).`
);
